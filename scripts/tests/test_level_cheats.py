"""scripts/sandbox/level_cheats.py: the one-byte "Allow Cheats" edit of a level.dat.

A world generated by the vanilla dedicated server has `allowCommands: 0`; opened in
single-player it refuses the /fill, /give and /tp an arena builds with. The fixture is a real
NBT layout (root compound > Data compound > byte tags), and the neighbours of the target byte
vary, so an off-by-one edit shows up as a changed neighbour, not as a pass.

Stdlib-only (unittest):
    python3 -m unittest discover -s scripts/tests -v
"""
from __future__ import annotations

import contextlib
import gzip
import io
import struct
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts" / "sandbox"))
import level_cheats  # noqa: E402


def _byte(name: str, value: int) -> bytes:
    n = name.encode()
    return b"\x01" + struct.pack(">H", len(n)) + n + bytes([value])


def level_dat(allow: int, *, extra: bytes = b"") -> bytes:
    """Root compound "" > compound "Data" > hardcore 7, allowCommands <allow>, Difficulty 9."""
    data = _byte("hardcore", 7) + _byte("allowCommands", allow) + _byte("Difficulty", 9) + extra
    inner = b"\x0a" + struct.pack(">H", 4) + b"Data" + data + b"\x00"
    return b"\x0a" + struct.pack(">H", 0) + inner + b"\x00"


class AllowCommandsTests(unittest.TestCase):
    def test_flips_only_the_target_byte(self) -> None:
        before = level_dat(0)
        after, old = level_cheats.allow_commands(before)
        self.assertEqual(old, 0)
        self.assertEqual(after, level_dat(1))
        self.assertEqual(len(after), len(before))
        diff = [i for i, (a, b) in enumerate(zip(before, after, strict=True)) if a != b]
        self.assertEqual(len(diff), 1)  # neighbours 7 and the Difficulty tag are untouched

    def test_already_on_is_a_no_op(self) -> None:
        nbt = level_dat(1)
        self.assertEqual(level_cheats.allow_commands(nbt), (nbt, 1))

    def test_no_tag_is_refused(self) -> None:  # NEG-CONTROL
        with self.assertRaises(ValueError):
            level_cheats.allow_commands(level_dat(0).replace(b"allowCommands", b"allowCommandz"))

    def test_two_tags_are_refused(self) -> None:  # NEG-CONTROL: never guess which one
        with self.assertRaises(ValueError):
            level_cheats.allow_commands(level_dat(0, extra=_byte("allowCommands", 0)))

    def test_a_truncated_tag_is_refused(self) -> None:  # NEG-CONTROL
        nbt = level_dat(0)
        cut = nbt[: nbt.find(b"allowCommands") + len(b"allowCommands")]
        with self.assertRaises(ValueError):
            level_cheats.allow_commands(cut)


class CliTests(unittest.TestCase):
    def test_rewrites_the_gzip_file_in_a_world_dir(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "level.dat"
            p.write_bytes(gzip.compress(level_dat(0)))
            with contextlib.redirect_stdout(io.StringIO()) as out:
                self.assertEqual(level_cheats.main([d]), 0)
            self.assertEqual(gzip.decompress(p.read_bytes()), level_dat(1))
            self.assertIn("allowCommands 0 -> 1", out.getvalue())

    def test_a_refused_file_is_left_untouched(self) -> None:  # NEG-CONTROL
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "level.dat"
            raw = gzip.compress(level_dat(0, extra=_byte("allowCommands", 0)))
            p.write_bytes(raw)
            with self.assertRaises(ValueError):
                level_cheats.main([str(p)])
            self.assertEqual(p.read_bytes(), raw)


if __name__ == "__main__":
    unittest.main()
