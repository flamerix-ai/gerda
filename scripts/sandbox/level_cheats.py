#!/usr/bin/env python3
"""level_cheats.py — turn "Allow Cheats" on in a single-player world's level.dat.

The test-root worlds are generated by the vanilla DEDICATED server (sbx.sh gen_world), and a
server writes `allowCommands: 0`. Opened in single-player, that world refuses /fill, /setblock,
/give and /tp — the commands an arena builds its scene with (scripts/dev/arena.py). This flips
the one NBT byte `Data.allowCommands` to 1, the same flag the "Allow Cheats" button of the
Create World screen sets.

    python3 level_cheats.py <world dir or level.dat>

The edit is byte-exact: level.dat is gzip'd NBT, and the tag is a TAG_Byte named
`allowCommands` (type 1, name length 13), so its value is the byte right after that header.
Exactly one such tag must exist; zero or several is refused, the file is left untouched.
"""
from __future__ import annotations

import gzip
import sys
from pathlib import Path

TAG = b"\x01\x00\x0dallowCommands"  # TAG_Byte, u16 name length 13, name


def allow_commands(nbt: bytes) -> tuple[bytes, int]:
    """(decompressed NBT with allowCommands = 1, the value it had before)."""
    at = nbt.find(TAG)
    if at < 0:
        raise ValueError("no allowCommands tag in level.dat")
    if nbt.find(TAG, at + 1) >= 0:
        raise ValueError("more than one allowCommands tag in level.dat")
    pos = at + len(TAG)
    if pos >= len(nbt):
        raise ValueError("level.dat ends inside the allowCommands tag")
    return nbt[:pos] + b"\x01" + nbt[pos + 1 :], nbt[pos]


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    p = Path(argv[0])
    if p.is_dir():
        p = p / "level.dat"
    nbt, before = allow_commands(gzip.decompress(p.read_bytes()))
    if before != 1:
        p.write_bytes(gzip.compress(nbt))
    print(f"{p}: allowCommands {before} -> 1")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
