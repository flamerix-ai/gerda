class SpecError(RuntimeError):
    """A spec, a snapshot box or a bridge block-read that is not usable as-is.

    Every snapshot failure mode raises this instead of degrading: a set that silently
    dropped half a box would restage a WRONG world and only show it in the take.
    """


def _default_inst() -> Path:
    return local_config.instance_dir(local_config.get("humanInstance", "Monifactory")) / "minecraft"


def _world_store_path() -> Path:
    # MC_INST (which instance's world store a `marker` op writes) is resolved in local_config,
    # the one home for it — so a typo'd path fails loudly here too instead of writing a marker
    # into a directory nobody reads.
    inst = local_config.mc_inst_override() or _default_inst()
    return inst / WORLD_STORE_REL


def _chat(c: BridgeClient, msg: str) -> None:
    c.send("chat", {"message": msg})


def _quiet(c: BridgeClient, on: bool) -> None:
    """Silence vanilla command SUCCESS feedback while we spam /fill + /setblock ('Successfully
    filled …'). `sendCommandFeedback` gates only successes: vanilla always sends failures to the
    issuer, so 'No blocks were filled' and the red 'Could not set the block' (a no-op setblock,
    the block already has that value) still reach the chat. One line each way."""
    _chat(c, f"/gamerule sendCommandFeedback {'false' if not on else 'true'}")


@contextlib.contextmanager
def _world_writes(c: BridgeClient, ops: list[dict]) -> Iterator[None]:
    """Command feedback off and a forceload ticket on the build's chunks while build() / clean() write.

    On a fresh world nobody stands near the arena: every /fill answered "That position is not
    loaded", the bot was teleported into the untouched world (ocean at 0,0) and drowned. The
    ticket is removed again when the writes are done (the bot standing there keeps its own
    chunks loaded), so a film set leaves no forced chunks behind. Op-only, like the fills.

    The ticket add sits inside the guarded block: an add that fails (dead bridge, not op) still
    turns feedback back on, and a remove of a ticket that never landed is harmless. The teardown
    sends both commands whatever happened. When the writes raised, a teardown failure only warns:
    a dead bridge must not mask the error that ended the writes. When they went through, it
    raises: a build or clean that exits normally has left no ticket and no feedback off.
    """
    box = forceload_box(ops)
    teardown = [] if box is None else ["/forceload remove {} {} {} {}".format(*box)]
    teardown.append("/gamerule sendCommandFeedback true")
    _quiet(c, False)
    wrote = False
    try:
        if box is not None:
            _chat(c, "/forceload add {} {} {} {}".format(*box))
            time.sleep(FORCELOAD_SETTLE_S)
        yield
        wrote = True
    finally:
        failure: Exception | None = None
        for cmd in teardown:
            try:
                _chat(c, cmd)
            except Exception as e:  # noqa: BLE001
                print(f"  ⚠ {cmd} failed: {e} — run it from the server console")
                failure = failure or e
        if wrote and failure is not None:
            raise failure


def _xyz(v: list) -> tuple[int, int, int]:
    return int(v[0]), int(v[1]), int(v[2])


# ── build ops ───────────────────────────────────────────────────────────────
def _apply_op(c: BridgeClient, op: dict) -> None:
    kind = op["op"]
    if kind == "clear":
        a, b = _xyz(op["from"]), _xyz(op["to"])
        _chat(c, f"/fill {a[0]} {a[1]} {a[2]} {b[0]} {b[1]} {b[2]} minecraft:air")
    elif kind == "fill":
        a, b = _xyz(op["from"]), _xyz(op["to"])
        _chat(c, f"/fill {a[0]} {a[1]} {a[2]} {b[0]} {b[1]} {b[2]} {op['block']}")
    elif kind == "set":
        p = _xyz(op["pos"])
        _chat(c, f"/setblock {p[0]} {p[1]} {p[2]} {op['block']}")
    elif kind == "clearinv":
        _chat(c, "/clear @s")
    elif kind == "give":
        _chat(c, f"/give @s {op['item']} {int(op.get('count', 1))}")
    elif kind == "select":
        c.send("key", {"key": f"key.hotbar.{int(op['slot']) + 1}"})
    elif kind == "player":
        p = _xyz(op["pos"])
        _chat(c, f"/tp @s {p[0] + 0.5} {p[1]} {p[2] + 0.5}")
    elif kind == "marker":
        _seed_marker(c, op["ore"], int(op["x"]), int(op["z"]))
    elif kind == "wait":
        time.sleep(int(op["ticks"]) / 20.0)
    else:
        raise ValueError(f"unknown op: {kind}")


def _sig_valid(sig: str) -> bool:
    """A world signature is 'wid|dim' with BOTH parts resolved. Right after a worker halt/start the
    client's world identity isn't synced yet, so main.js publishes a transient fallback like
    'UNKNOWN_NAME|null' (see harness/world_store.js worldSignature()). Seeding a drill marker into
    that section lands it where the booted worker never reads (it resolves 'localhost|minecraft:overworld'
    once synced) — the drill then finds no vein. Reject the transient forms so seeding waits for the
    real thing."""
    wid, sep, dim = sig.partition("|")
    if not sep or not wid or not dim:
        return False
    return "UNKNOWN_NAME" not in wid and dim not in ("null", "undefined")


def _world_sig(c: BridgeClient, *, timeout: float = 12.0) -> str:
    """The active world signature (the world-store section key) main.js publishes — polled until it
    SETTLES to a real, non-transient value. Post-restart the sig briefly reads 'UNKNOWN_NAME|null'; a
    marker seeded into that phantom section is invisible to the drill (the live-run drill-FAIL bug this
    session chased). Require a valid sig that repeats on a re-read before trusting it."""
    deadline = time.time() + timeout
    last: str | None = None
    stable = 0
    while time.time() < deadline:
        r = c.send("jeval", {"code": "GlobalVars.getString('mc_world_sig');"})
        sig = r.get("data")
        if sig and _sig_valid(str(sig)):
            sig = str(sig)
            stable = stable + 1 if sig == last else 0
            last = sig
            if stable >= 1:  # same valid value on two consecutive reads → settled
                return sig
        else:
            last = None
            stable = 0
        time.sleep(0.3)
    if last and _sig_valid(last):
        return last  # valid but never re-confirmed — better than a transient section
    raise RuntimeError(f"world signature never settled to a real value (last={last!r})")


def _seed_marker(c: BridgeClient, ore: str, x: int, z: int) -> None:
    """Append a prospector resource (the drill mission targets the nearest cached vein) to
    the world store's active section, host-side. Done right before mission_start so the
    drill's init reads it fresh (the worker only persists on its own changes)."""
    sig = _world_sig(c)
    path = _world_store_path()
    store = json.loads(path.read_text("utf-8")) if path.exists() else {"version": 1, "worlds": {}}
    worlds = store.setdefault("worlds", {})
    section = worlds.setdefault(
        sig,
        {"waypoints": [], "resources": [], "stats": {"dumps": 0, "veinsFound": 0, "boots": 0}, "updatedAt": 0},
    )
    res = section.setdefault("resources", [])
    res[:] = [r for r in res if not (r.get("x") == x and r.get("z") == z)]  # dedupe the cell
    res.append({"kind": ore, "x": x, "z": z})
    # Honor the mc_world.json multi-writer compare-and-swap protocol: bump the monotonic `seq` and write
    # ATOMICALLY (temp + os.replace, POSIX-atomic within a dir) so an in-game reader never sees a torn
    # file. This host seeder is low-contention (bot idle at seed time) — the atomic rename is the load-
    # bearing half; a bot writer that raced would re-merge on its own seq conflict.
    store["seq"] = int(store.get("seq") or 0) + 1
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(store, ensure_ascii=False), "utf-8")
    os.replace(tmp, path)
    print(f"  seeded marker {ore} @ ({x},{z}) in {sig} (seq={store['seq']})")


# ── snapshot: live world → ops (the PURE half) ────────────────────────────────
# `snapshot` reads the blocks of every declared box out of the running game and rewrites
# spec["ops_generated"] so `build` can restage that exact volume later. Everything in this
# section is pure data-in/data-out (no bridge, no game) — that is what makes the compression
# and the 1:1 round-trip unit-testable offline (scripts/tests/test_arena_snapshot.py).

AIR = "minecraft:air"
# Namespaced block id, the only shape /fill and /setblock accept. A read that yields
# anything else (an empty string = World.getBlock returned null on an UNLOADED chunk, or a
# truncated reply) is a hard error: writing it into a spec would produce a build that fails
# block-by-block in chat, hours later.
BLOCK_ID_RE = re.compile(r"^[a-z0-9_.-]+:[a-z0-9_./-]+$")
# Fluids are captured by ID, which cannot tell a SOURCE block from flowing water — the
# difference lives in the blockstate `level`, which getBlock().getId() drops. Restaging one
# therefore writes a permanent SOURCE: snapshot the mesa-clutch corridor with the clutch water
# still in it and every rebuild pours an eternal waterfall down the fall column. So a fluid in
# a snapshot box is refused outright: drain/scoop the set and re-read it dry.
FLUID_IDS = frozenset({"minecraft:water", "minecraft:lava", "minecraft:bubble_column"})
# Per declared box, and NOT a taste knob: 32768 is vanilla `/fill`'s hard block limit, so a
# base op covering a bigger box would be REJECTED by the server and the restage would come out
# half-built. The cap keeps every generated op executable by construction.
SNAPSHOT_MAX_CELLS = 32768
# Per bridge round-trip. The read loop runs inside main.js's sandboxed `eval` on the
# container thread; jsMacros' EventLockWatchdog kills a handler that blocks >500 ms (and can
# drop the world), so a box is split into sub-boxes of at most this many World.getBlock calls.
# It also bounds the REPLY: bridge.js frames one response per line, and a worst-case
# alternating box encodes to ~2 ints per cell, i.e. a ~12 KB line at this size.
SNAPSHOT_READ_CELLS = 2000
# A snapshot read is a bounded loop, but a cold chunk + a 2000-cell box is slower than a
# status ping — the default 5 s socket timeout would abort a perfectly healthy read.
SNAPSHOT_TIMEOUT = 30.0
# The WRITE side's twin of SNAPSHOT_MAX_CELLS. Every op is one chat round-trip, so a runaway
# op list (a mis-declared box that compressed into thousands of exceptions) would spend minutes
# spraying /setblock at the world before anyone could tell it was wrong. Refuse it up front —
# never truncate: a half-built set is exactly the silently-wrong stage this file exists to stop.
BUILD_MAX_OPS = 2000
# Progress cadence for that loop, so a long build is visibly alive rather than mute (mirrors the
# per-sub-box `read n/N` line on the snapshot side).
BUILD_PROGRESS_EVERY = 25
# What a dimension read must NEVER be taken for a dimension. `World.getDimension()` really does
# return null on a client that is between worlds (harness/world_store.js keys such a session
# `<server>|null`, and live mc_world.json files carry those sections), and the `"" + …` coercion
# the read rides turns that null into the 4-character STRING "null" — which sails through a bare
# non-empty check and would get STAMPED into a spec as its capture dimension.
DIMENSION_SENTINELS = frozenset({"null", "undefined"})

Vec = tuple[int, int, int]


def box_bounds(box: dict) -> tuple[Vec, Vec]:
    """Normalise a {"from":[…],"to":[…]} box to (lo, hi) inclusive corners."""
    if not isinstance(box, dict) or "from" not in box or "to" not in box:
        raise SpecError(f"snapshot box needs both 'from' and 'to': {box!r}")
    a, b = _xyz(box["from"]), _xyz(box["to"])
    lo = (min(a[0], b[0]), min(a[1], b[1]), min(a[2], b[2]))
    hi = (max(a[0], b[0]), max(a[1], b[1]), max(a[2], b[2]))
    return lo, hi


def box_volume(lo: Vec, hi: Vec) -> int:
    return (hi[0] - lo[0] + 1) * (hi[1] - lo[1] + 1) * (hi[2] - lo[2] + 1)


def box_cells(lo: Vec, hi: Vec) -> list[Vec]:
    """Every cell of the box in the canonical READ ORDER: y outer, then z, then x."""
    return [
        (x, y, z)
        for y in range(lo[1], hi[1] + 1)
        for z in range(lo[2], hi[2] + 1)
        for x in range(lo[0], hi[0] + 1)
    ]


def split_box(lo: Vec, hi: Vec, cap: int = SNAPSHOT_READ_CELLS) -> list[tuple[Vec, Vec]]:
    """Split a box into sub-boxes of at most `cap` cells by halving its longest axis.

    Deterministic and exact — the sub-boxes tile the parent with no gap and no overlap, so
    stitching their reads back together can never silently lose a cell.
    """
    if cap < 1:
        raise SpecError(f"split cap must be >= 1 (got {cap})")
    if box_volume(lo, hi) <= cap:
        return [(lo, hi)]
    spans = [hi[i] - lo[i] for i in range(3)]
    axis = spans.index(max(spans))
    if spans[axis] == 0:  # a 1x1x1 box already exceeds the cap — impossible, but never loop
        raise SpecError(f"cannot split a single cell to fit cap={cap}")
    mid = lo[axis] + spans[axis] // 2
    hi_a: Vec = (mid if axis == 0 else hi[0], mid if axis == 1 else hi[1], mid if axis == 2 else hi[2])
    lo_b: Vec = (
        mid + 1 if axis == 0 else lo[0],
        mid + 1 if axis == 1 else lo[1],
        mid + 1 if axis == 2 else lo[2],
    )
    return split_box(lo, hi_a, cap) + split_box(lo_b, hi, cap)


def snapshot_js(lo: Vec, hi: Vec) -> str:
    """The sandboxed-`eval` expression that reads one sub-box as a palette + RLE run list.

    Constraints this code is shaped by (harness/main.js safeEval):
      • the sandbox wraps the code in `return( … )`, so it must be a single EXPRESSION;
      • BANNED_PATTERNS rejects `while(`, `for(;;)`, `do{` and the word `java` — the counted
        `for` loops below are the only legal loop form (a drift guard asserts this in the tests);
      • the reply is one newline-framed JSON line, so it is palette-encoded + run-length
        compressed here rather than shipping one id per cell.
    getBlock returns null on an UNLOADED chunk — that is NOT air, so it is encoded as the
    empty id and rejected host-side (parse_block_reply).
    """
    return (
        "(function(){var P=[],M={},R=[],last=-1,run=0;"
        f"for(var y={lo[1]};y<={hi[1]};y++)"
        f"{{for(var z={lo[2]};z<={hi[2]};z++)"
        f"{{for(var x={lo[0]};x<={hi[0]};x++){{"
        'var b=World.getBlock(x,y,z);var id=b?b.getId():"";'
        "var i=M[id];if(i===undefined){i=P.length;M[id]=i;P.push(id);}"
        "if(i===last){run++;}else{if(last>=0){R.push(last);R.push(run);}last=i;run=1;}"
        "}}}"
        "if(last>=0){R.push(last);R.push(run);}"
        "return {p:P,r:R};})()"
    )


def parse_block_reply(reply: object, lo: Vec, hi: Vec) -> dict[Vec, str]:
    """Decode one `eval` reply (palette + RLE) into {cell: block_id} for the sub-box.

    Fail-loud on every shape that is not exactly the box we asked for: a bridge error, a
    non-object payload, a palette entry that is not a namespaced id (the unloaded-chunk
    sentinel lands here), an out-of-range palette index, or a run total that does not equal
    the box volume.
    """
    if not isinstance(reply, dict):
        raise SpecError(f"block read: bridge returned {type(reply).__name__}, not an object")
    if not reply.get("ok"):
        raise SpecError(f"block read failed: {reply.get('error') or reply!r}")
    data = reply.get("data")
    if not isinstance(data, dict):
        raise SpecError(f"block read: reply has no data object (got {data!r})")
    palette, runs = data.get("p"), data.get("r")
    if not isinstance(palette, list) or not isinstance(runs, list):
        raise SpecError(f"block read: malformed payload keys p/r (got {data!r})")
    for entry in palette:
        if not isinstance(entry, str) or not BLOCK_ID_RE.match(entry):
            raise SpecError(
                f"block read: bad block id {entry!r} — an empty id means World.getBlock "
                "returned null (chunk NOT loaded); fly the reading client to the set first"
            )
    if len(runs) % 2 != 0:
        raise SpecError(f"block read: odd run list ({len(runs)} entries, want pairs)")
    cells = box_cells(lo, hi)
    flat: list[str] = []
    for i in range(0, len(runs), 2):
        idx, count = runs[i], runs[i + 1]
        if not isinstance(idx, int) or not isinstance(count, int) or count < 1:
            raise SpecError(f"block read: bad run pair ({idx!r},{count!r})")
        if not 0 <= idx < len(palette):
            raise SpecError(f"block read: palette index {idx} out of range (size {len(palette)})")
        # Budget-check BEFORE materialising: a corrupt run count (r=[0, 2**31]) would otherwise
        # allocate the list first and only then be told it is too long.
        if count > len(cells) - len(flat):
            raise SpecError(
                f"block read: runs overflow the box (at least {len(flat) + count} cells, "
                f"box holds {len(cells)})"
            )
        flat.extend([palette[idx]] * count)
    if len(flat) != len(cells):
        raise SpecError(f"block read: got {len(flat)} cells, box holds {len(cells)}")
    fluid = next((i for i, b in enumerate(flat) if b in FLUID_IDS), None)
    if fluid is not None:
        raise SpecError(
            f"block read: {flat[fluid]} at {cells[fluid]} — a fluid cannot be snapshotted "
            "(id-only capture loses the source-vs-flowing state, so a restage would write a "
            "PERMANENT source block). Drain/scoop the set and snapshot it DRY."
        )
    return dict(zip(cells, flat, strict=True))


def _merge_boxes(cells: dict[Vec, str]) -> list[tuple[Vec, Vec, str]]:
    """Greedy-mesh same-id cells into maximal axis-aligned boxes (x, then z, then y).

    An ore-lined chamber wall is ~140 identical cells; without merging that is 140 chat
    /setblock round-trips per rebuild. Deterministic: cells are consumed in (y,z,x) order.
    """
    remaining = dict(cells)
    out: list[tuple[Vec, Vec, str]] = []
    for cell in sorted(cells, key=lambda c: (c[1], c[2], c[0])):
        if cell not in remaining:
            continue
        x, y, z = cell
        bid = remaining[cell]
        x1 = x
        while remaining.get((x1 + 1, y, z)) == bid:
            x1 += 1
        z1 = z
        while all(remaining.get((xx, y, z1 + 1)) == bid for xx in range(x, x1 + 1)):
            z1 += 1
        y1 = y
        while all(
            remaining.get((xx, y1 + 1, zz)) == bid
            for xx in range(x, x1 + 1)
            for zz in range(z, z1 + 1)
        ):
            y1 += 1
        for xx in range(x, x1 + 1):
            for yy in range(y, y1 + 1):
                for zz in range(z, z1 + 1):
                    del remaining[(xx, yy, zz)]
        out.append(((x, y, z), (x1, y1, z1), bid))
    return out


def compress_box(lo: Vec, hi: Vec, cells: dict[Vec, str]) -> list[dict]:
    """Turn one read box into the smallest op list that restages it 1:1 — AIR INCLUDED.

    Shape: one BASE op covering the whole box with its dominant block (`clear` when that is
    air, else `fill`), then the merged exception boxes on top (`fill` for a run, `set` for a
    lone cell). Air is never "skipped": a set whose corridor was carved out must restage as
    carved, so the base op wipes the volume before the exceptions land.
    """
    missing = [c for c in box_cells(lo, hi) if c not in cells]
    if missing:
        raise SpecError(f"compress: {len(missing)} cells missing from the read (e.g. {missing[0]})")
    counts = Counter(cells[c] for c in box_cells(lo, hi))
    # max by (count, id) — the id tie-break keeps the generat byte-identical between runs.
    dominant = max(counts.items(), key=lambda kv: (kv[1], kv[0]))[0]
    base: dict = (
        {"op": "clear", "from": list(lo), "to": list(hi)}
        if dominant == AIR
        else {"op": "fill", "from": list(lo), "to": list(hi), "block": dominant}
    )
    ops: list[dict] = [base]
    exceptions = {c: b for c, b in cells.items() if b != dominant}
    for blo, bhi, bid in _merge_boxes(exceptions):
        if blo == bhi:
            ops.append({"op": "set", "pos": list(blo), "block": bid})
        else:
            ops.append({"op": "fill", "from": list(blo), "to": list(bhi), "block": bid})
    return ops


def apply_ops(ops: list[dict]) -> dict[Vec, str]:
    """Replay the BLOCK ops of a spec onto an in-memory grid (the offline twin of `build`).

    Only the world ops are modelled (clear/fill/set); kit/teleport/marker/wait ops touch no
    block. This is what lets the tests assert a real 1:1 round-trip — snapshot → ops →
    replay → the original grid — instead of merely eyeballing the op list.
    """
    grid: dict[Vec, str] = {}
    for op in ops:
        kind = op.get("op")
        if kind in ("clear", "fill"):
            lo, hi = box_bounds(op)
            block = AIR if kind == "clear" else op["block"]
            for cell in box_cells(lo, hi):
                grid[cell] = block
        elif kind == "set":
            grid[_xyz(op["pos"])] = op["block"]
    return grid


def validate_set_spec(spec: dict, name: str) -> None:
    """A film set is NOT an arena: no mission, no plan, no expect, and a snapshot decl.

    The forbidden keys are the load-bearing half — a set that carried a `mission` would be a
    live-behaviour test living outside scenarios/arenas, i.e. outside `just gate-live`, and
    would rot unrun.
    """
    for key in ("mission", "plan", "expect", "checks", "known_bad"):  # gate:set-refuses-checks
        if key in spec:
            raise SpecError(
                f"set '{name}' declares '{key}' — film sets stage the world only; a spec that "
                "runs a mission belongs in scenarios/arenas/ where the gate runs it"
            )
    snap = spec.get("snapshot")
    if not isinstance(snap, dict):
        raise SpecError(f"set '{name}' has no 'snapshot' object (declare the boxes to capture)")
    boxes = snap.get("boxes")
    if not isinstance(boxes, list) or not boxes:
        raise SpecError(f"set '{name}': snapshot.boxes must be a non-empty list")
    # Optional, and STAMPED by `snapshot` from the live client — but if it is there it must be a
    # real dimension id, because `build` compares the client against it and refuses a mismatch. A
    # null/number/empty `dimension` would make that comparison meaningless in the one direction
    # that matters (guard present, guard toothless).
    if "dimension" in snap:
        dim = snap["dimension"]
        if not isinstance(dim, str) or not dim.strip() or dim in DIMENSION_SENTINELS or ":" not in dim:
            raise SpecError(
                f"set '{name}': snapshot.dimension must be a namespaced dimension id like "
                f"'minecraft:overworld' (got {dim!r}) — it is stamped by `snapshot` from the "
                "client that read the boxes, and a hand-written stamp must clear the same bar"
            )
    for i, box in enumerate(boxes):
        lo, hi = box_bounds(box)
        vol = box_volume(lo, hi)
        if vol > SNAPSHOT_MAX_CELLS:
            raise SpecError(
                f"set '{name}': snapshot box {i} spans {vol} cells > cap {SNAPSHOT_MAX_CELLS} "
                "— tighten the box (a set is a stage, not a chunk dump)"
            )
    for key in ("ops", "ops_generated"):
        if key in spec and not isinstance(spec[key], list):
            raise SpecError(f"set '{name}': '{key}' must be a list")


def _client_dimension(c: BridgeClient) -> str:
    """The dimension the DRIVEN client is standing in, read over the sandboxed `eval`.

    A box is a bare (x,y,z) volume with no world attached, so a bot parked in the wrong
    dimension (javd:void after a `/spawn`, the Nether after a portal) reads a perfectly
    well-formed all-air snapshot and restages the set into a world nobody films. Nothing
    downstream can tell — hence this one extra read.

    `World.getDimension()` is the same identity harness/world_store.js keys the world store by,
    and a plain `"" + …` expression clears the sandbox's BANNED_PATTERNS (no loop, no `java`).
    Fail-loud on anything that is not a REAL dimension id: an UNREADABLE dimension must abort
    exactly as hard as a wrong one, or the guard degrades into a coin flip.

    Two shapes of "unreadable" both have to die here, and only one is obvious:
      * empty/non-string — the reply never carried an id at all;
      * the STRINGIFIED nulls. `getDimension()` returns null on a client between worlds (a real
        transient on this machine: live mc_world.json files carry `UNKNOWN_NAME|null` sections),
        and `"" + null` is the 4-character string "null" — a non-empty string that would pass a
        naive check and get stamped as a spec's capture dimension. A `--wait-ready` that has just
        returned is exactly when that window is open, so it is the likely case, not an exotic one.
    Real ids are namespaced (`minecraft:overworld`, `javd:void` — every key in every live world
    store), so the `:` is a cheap, evidence-backed second gate on the same failure.
    """
    reply = c.send("eval", {"code": '"" + World.getDimension()'})
    if not isinstance(reply, dict):
        raise SpecError(f"dimension read: bridge returned {type(reply).__name__}, not an object")
    if not reply.get("ok"):
        raise SpecError(f"dimension read failed: {reply.get('error') or reply!r}")
    dim = reply.get("data")
    dim = dim.strip() if isinstance(dim, str) else dim
    if not isinstance(dim, str) or not dim or dim in DIMENSION_SENTINELS or ":" not in dim:
        raise SpecError(
            f"dimension read came back UNUSABLE ({dim!r}) — a dimension id is a namespaced string "
            "like 'minecraft:overworld'; this is what a client that is not (yet) in a world reads "
            "as, a transient. Wait until the client has FULLY entered the world and retry (a bare "
            "`--wait-ready` return is not enough — check `get_state` reports a position)"
        )
    return dim


def _assert_dimension(c: BridgeClient, spec: dict) -> None:
    """Refuse to BUILD a snapshot-backed spec anywhere but the dimension it was captured in.

    Only sets carry a `snapshot` section — an arena is a hand-written stage and is exempt.
    A spec written before this guard existed has no stamp at all; that is refused too rather
    than assumed-fine, since "no stamp" and "right dimension" are indistinguishable from here.
    """
    snap = spec.get("snapshot")
    if not isinstance(snap, dict):
        return  # an arena: no captured world to be in the wrong copy of
    # `name` is injected by _load, but this is also called on hand-built specs (tests, callers
    # that assembled a spec themselves) — a KeyError here would mask the guard it is reporting.
    name = spec.get("name", "<unnamed>")
    declared = snap.get("dimension")
    client_dim = _client_dimension(c)
    if not declared:
        raise SpecError(
            f"'{name}' has no snapshot.dimension — the spec predates the dimension guard "
            f"(this client is in {client_dim}). Re-snapshot the set while its world is intact to "
            "stamp it, or hand-stamp snapshot.dimension only after manually verifying which "
            "dimension the boxes were captured in"
        )
    if declared != client_dim:
        raise SpecError(
            f"'{spec['name']}' was captured in {declared}, but this client is in {client_dim} — "
            "building here would stage the set into the WRONG world (and a snapshot taken here "
            "would capture bare air). Move the driving client to the set's dimension"
        )


def _read_box(c: BridgeClient, lo: Vec, hi: Vec) -> dict[Vec, str]:
    """Read one box off the LIVE world, in watchdog-safe sub-box chunks."""
    cells: dict[Vec, str] = {}
    subs = split_box(lo, hi)
    for n, (slo, shi) in enumerate(subs, 1):
        reply = c.send("eval", {"code": snapshot_js(slo, shi)})
        cells.update(parse_block_reply(reply, slo, shi))
        print(f"    read {n}/{len(subs)} {slo}→{shi} ({box_volume(slo, shi)} cells)")
    return cells


def verify_build(c: BridgeClient, spec: dict) -> None:
    """Re-read ONE sub-box of a freshly built set and prove the world matches the ops.

    Without this, `build` is a WRITE-ONLY path with a silent failure mode: block ops go out as
    chat `/fill`/`/setblock`, and a NON-OP sender has every one of them rejected server-side.
    `_chat` never sees that rejection, so the run prints "N ops applied" and exits 0 over a
    world nothing happened to (bots are non-op by design — drive `build` from the OP camera
    client, or op the bot for the session as `just gate-live` does).

    One extra bridge call: the first sub-box of the first snapshot box, compared against the
    grid the ops claim to have written.
    """
    expected = apply_ops(_build_ops(spec))
    lo, hi = box_bounds(spec["snapshot"]["boxes"][0])
    slo, shi = split_box(lo, hi)[0]
    live = _read_box(c, slo, shi)
    bad = [(cell, expected[cell], live[cell]) for cell in box_cells(slo, shi) if live[cell] != expected[cell]]
    if bad:
        cell, want, got = bad[0]
        raise SpecError(
            f"post-build verify FAILED: {len(bad)}/{len(live)} cells differ in {slo}→{shi} "
            f"(e.g. {cell}: want {want}, got {got}). The commonest cause is a NON-OP client — "
            "the server silently rejects /fill and /setblock from a bot sender, and nothing in "
            "the chat path reports it. Build from an OPPED client."
        )
    print(f"  verified {len(live)} cells of {slo}→{shi} against the ops")


def snapshot(c: BridgeClient, name: str, spec: dict) -> None:
    """Capture every declared box off the live world into spec["ops_generated"] and save.

    THE INPUT IS `snapshot.boxes`; `ops_generated` is the OUTPUT — edit the boxes and re-run,
    never the ops. Hand-written `ops` (give/player/marker/…) are preserved untouched.
    """
    validate_set_spec(spec, name)
    # BEFORE any block is read: a bot in javd:void answers every getBlock with air, so an
    # unguarded re-snapshot would overwrite a good generat with a plausible empty one.
    client_dim = _client_dimension(c)
    declared = spec["snapshot"].get("dimension")
    if declared and declared != client_dim:
        raise SpecError(
            f"set '{name}' was captured in {declared}, but this client is in {client_dim} — "
            "re-snapshotting from here would overwrite the generat with the wrong world. Move "
            "the driving client to the set's dimension (or drop the stamp deliberately if the "
            "set really did move)"
        )
    if not declared and spec.get("ops_generated"):
        raise SpecError(
            f"set '{name}' already carries a generat ({len(spec['ops_generated'])} ops) but no "
            "snapshot.dimension stamp — a blind re-capture could replace a good generat with a "
            "plausible all-air one read from the wrong world. Hand-stamp snapshot.dimension "
            "after verifying which dimension the ops came from, or empty ops_generated for a "
            "genuine first capture"
        )
    # First snapshot stamps it; later ones re-write the identical value, so a re-snapshot of an
    # unchanged world stays a zero-diff.
    spec["snapshot"]["dimension"] = client_dim
    print(f"  dimension {client_dim}")
    boxes = spec["snapshot"]["boxes"]
    generated: list[dict] = []
    for i, box in enumerate(boxes):
        lo, hi = box_bounds(box)
        print(f"  box {i}: {lo}→{hi} ({box_volume(lo, hi)} cells)")
        ops = compress_box(lo, hi, _read_box(c, lo, hi))
        print(f"    → {len(ops)} ops")
        generated.extend(ops)
    # A capture that can never build must die at capture time, BEFORE the spec is written —
    # the budget error's cure ("tighten the boxes and re-snapshot") only works while the world
    # the boxes describe is still intact.
    _check_op_budget(generated + list(spec.get("ops") or []), name)
    spec["ops_generated"] = generated
    _write_spec(name, spec)
    print(f"snapshot '{name}': {len(generated)} generated ops written to {_spec_path(name)}")


