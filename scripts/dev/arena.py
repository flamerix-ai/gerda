#!/usr/bin/env python3
"""arena.py — declarative in-game test-arena/film-set builder, runner and snapshotter.

A test arena is a JSON spec (scenarios/arenas/<name>.json): a list of build OPS, the
mission to run, and the log EVENTS that prove it worked. This tool builds the structure
(/fill, /setblock), kits the bot (/clear, /give, select), teleports it, seeds a prospector
marker (the drill mission reads veins from the world store), starts the mission, and polls
the logs to assert the expected events fired with no ERROR — a live e2e in one command:

    python scripts/dev/arena.py run bridge-gap          # build + run + verify
    python scripts/dev/arena.py build bridge-gap        # just build the structure
    python scripts/dev/arena.py clean bridge-gap        # clear its regions back to air
    python scripts/dev/arena.py list                     # list available arenas + film sets
    python scripts/dev/arena.py run --all                # run every arena, report pass/fail

A FILM SET is the same spec MINUS mission/plan/expect (scenarios/sets/<name>.json,
addressed as `sets/<name>`) PLUS a `snapshot` declaration — the shoot-day staging of the
teaser, captured as data so a re-shoot restages the world instead of rebuilding it by
hand. `--all` and `just gate-live` glob scenarios/arenas ONLY, so a set can never enter
the gate:

    python scripts/dev/arena.py snapshot sets/03_ore_chamber --port 55546   # LIVE world → ops
    python scripts/dev/arena.py build    sets/03_ore_chamber --port 55546   # data → world
    python scripts/dev/arena.py clean    sets/03_ore_chamber --port 55546   # back to air

`--port`/`--host` pick the client to drive (default 55544). Building a set REQUIRES an OPPED
client — the server silently drops `/fill` and `/setblock` from a non-op bot sender, so a build
against a bot "succeeds" over an unchanged world. `build <set>` therefore re-reads a sub-box
afterwards and FAILS LOUD if the world does not match the ops.

OPS (each a JSON object in spec["ops"] / spec["ops_generated"]):
    {"op":"clear","from":[x,y,z],"to":[x,y,z]}            fill region with air
    {"op":"fill","from":[...],"to":[...],"block":"id"}    fill region with a block
    {"op":"set","pos":[x,y,z],"block":"id"}               one block
    {"op":"clearinv"}                                     /clear @s (empty the bot)
    {"op":"give","item":"id","count":1}                   /give @s
    {"op":"select","slot":0}                              select hotbar slot 0-8 (key.hotbar.N+1)
    {"op":"player","pos":[x,y,z]}                          /tp the bot (TEST-only cheat)
    {"op":"marker","ore":"iron","x":X,"z":Z}              seed a drill target in the world store
    {"op":"wait","ticks":N}                               sleep N game-ticks (N/20 s)

SPEC keys: desc, snapshot {boxes:[{from,to}], dimension}, ops_generated, ops,
mission {name, params}, expect {events:[...], timeout: sec}, checks, known_bad (both below).
A spec's NAME is its filename — never a key in the file (one is refused on load). `snapshot.dimension` is stamped by `snapshot`
and checked by `build`, so a set can never be restaged into the wrong world.
Build order is ops_generated (the world) THEN ops (kit/teleport/marker); the
marker/mission/expect steps are applied after the build OPS (in that order).

**`ops_generated` IS A GENERAT.** It is written by `snapshot` from the live world and must
never be hand-edited: the INPUT is `snapshot.boxes`, the output is regenerated by re-running
`snapshot`. Hand-written setup (give/player/marker/select/wait, and any block a snapshot
cannot express) lives in `ops`, which `snapshot` never touches.

CHECKS — assertions on game state, no mission needed (the mod-testing path,
docs/MOD_TESTING.md). Each entry runs one `jeval` after the build (and after the mission
verdict, when there is a mission) and compares its JSON value with `expect`:
    {"desc":"what it proves", "jeval":"<JavaScript, full jsMacros/Java scope>", "expect":<json>}
A mismatch or a jeval error FAILS the arena; the line shows got vs expected.

KNOWN-BAD — a negative control: `"known_bad": "<the wrong behaviour it asserts>"` plus
`"wrong": true` on each check whose `expect` is wrong on purpose. Each marked check needs
exactly ONE unmarked TWIN in the same arena: the same `jeval`, with the right value as its
`expect` (load refuses the arena otherwise). A marked check PASSES only when its own reply
succeeded with exactly its twin's `expect` and the twin passed — the game refused the wrong
claim by giving the right answer. Every unmarked check, and the mission if there is one, must
pass as usual. A failed placement, a missing kit, a null or an error reply, or any other value
is a FAIL, never a pass. No verdict is inverted anywhere.

Build cheats (/fill, /give, /tp) are for TEST SETUP only — never used by mission logic.
"""
