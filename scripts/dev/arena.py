def _reset_worker(c: BridgeClient, delay_ms: int = 1200, timeout: float = 30.0) -> None:
    """Return the worker to a clean IDLE state before a mission, via the OFF-THREAD `reload_worker`
    (main.js does halt+start on a background thread, ack flushed first). A bare `halt`+`start` runs
    SM.stopService on main's Tick thread — if the worker is mid-op it BLOCKS main's dispatch and the
    whole bridge goes DEAF (the deaf-lock that wedged bot_1 mid-gate and forced a client
    relaunch). reload_worker never blocks main, so back-to-back arenas can't
    wedge it. Wait for the fresh worker to report running before returning."""
    # Gracefully stop any mission the PREVIOUS arena left running FIRST — an in-worker `pause` (releases
    # keys, nav.stop, → PAUSED; no main handler, so it routes to the worker). Without this, reload_worker's
    # off-thread halt collides with an in-flight mission/async-break and still deaf-locks main (what wedged
    # bot_1 between back-to-back drill arenas even after halt/start was removed).
    try:
        c.send("pause", {})
        time.sleep(1.0)
    except Exception:  # noqa: BLE001 — best-effort quiesce; reload_worker is the real reset
        pass
    try:
        c.send("reload_worker", {"delay": delay_ms})
    except TimeoutError:  # ack flushes before any work — a timeout means main is ALREADY deaf
        raise RuntimeError("reload_worker got no ack — bridge is deaf (restart the bot client)") from None
    time.sleep(delay_ms / 1000.0 + 1.0)  # let the deferred halt+start actually begin
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            if ((c.send("get_state", {}).get("worker") or {}).get("status")) == "running":
                return
        except Exception:  # noqa: BLE001 — worker mid-restart is briefly unreadable; keep polling
            pass
        time.sleep(1.0)
    # best effort: proceed even unconfirmed — a truly dead worker surfaces as a real arena FAIL


def _build_ops(spec: dict) -> list[dict]:
    """The full build sequence: the GENERATED world ops first, then the hand-written ones.

    Order is load-bearing — `ops_generated` fills the volume, so a `player` teleport or a
    `give` in `ops` must land after it, not under it.
    """
    ops = list(spec.get("ops_generated") or []) + list(spec.get("ops") or [])
    if not ops:
        raise SpecError(
            f"'{spec['name']}' has no ops to build — for a film set run `snapshot` against the "
            "live world first (ops_generated is a generat, not something you write by hand)"
        )
    return ops


def _check_op_budget(ops: list[dict], name: str) -> None:
    """Refuse an over-budget build outright (the pure half of the cap, so it is testable).

    No truncation: applying the first BUILD_MAX_OPS ops would leave a half-staged world that
    still exits 0 — the exact silent-wrong-stage failure the snapshot side already refuses.
    """
    if len(ops) > BUILD_MAX_OPS:
        raise SpecError(
            f"'{name}' builds {len(ops)} ops > cap BUILD_MAX_OPS={BUILD_MAX_OPS} — every op is a "
            "chat round-trip, so this is a mis-declared snapshot box (or a spec that wants "
            "splitting), not a slow build. Tighten the boxes and re-snapshot"
        )


# Seconds between `/forceload add` and the first write: forceload only adds a chunk ticket; the
# server loads (on a fresh world: generates) the chunks over the next ticks.
FORCELOAD_SETTLE_S = 3.0


def forceload_box(ops: list[dict]) -> tuple[int, int, int, int] | None:
    """The X/Z box (x1, z1, x2, z2) every positional op of a build touches, or None."""
    xs: list[int] = []
    zs: list[int] = []
    for op in ops:
        for key in ("from", "to", "pos"):
            if key in op:
                x, _y, z = _xyz(op[key])
                xs.append(x)
                zs.append(z)
        if op["op"] == "marker":
            xs.append(int(op["x"]))
            zs.append(int(op["z"]))
    if not xs:
        return None
    return min(xs), min(zs), max(xs), max(zs)


def build(c: BridgeClient, spec: dict) -> None:
    print(f"building '{spec['name']}': {spec.get('desc', '')}")
    # Both guards run BEFORE the first op leaves: a wrong-dimension or over-budget build must
    # not have written a single block into the world by the time it aborts.
    _assert_dimension(c, spec)
    ops = _build_ops(spec)
    _check_op_budget(ops, spec["name"])
    with _world_writes(c, ops):
        for k, op in enumerate(ops, 1):
            _apply_op(c, op)
            if k % BUILD_PROGRESS_EVERY == 0:
                print(f"  applied {k}/{len(ops)} ops")
    print(f"  {len(ops)} ops applied")


def clean(c: BridgeClient, spec: dict) -> None:
    """Clear every fill/clear/set region back to air (tidy up after a test)."""
    # Same two guards as build — and MORE load-bearing here, because clean is the destructive
    # path: it air-fills whole regions, so a client parked in the wrong dimension would erase
    # chunks of whatever world it is actually standing in, silently, exit 0.
    _assert_dimension(c, spec)
    ops = _build_ops(spec)
    _check_op_budget(ops, spec["name"])
    n = 0
    with _world_writes(c, ops):
        for op in ops:
            if op["op"] in ("clear", "fill"):
                a, b = _xyz(op["from"]), _xyz(op["to"])
                _chat(c, f"/fill {a[0]} {a[1]} {a[2]} {b[0]} {b[1]} {b[2]} minecraft:air")
                n += 1
            elif op["op"] == "set":
                p = _xyz(op["pos"])
                _chat(c, f"/setblock {p[0]} {p[1]} {p[2]} minecraft:air")
                n += 1
    print(f"cleared {n} regions for '{spec['name']}'")


def _recent_events(c: BridgeClient, n: int = 200) -> list[dict]:
    """Logs since the CURRENT worker boot only — get_logs returns a ring buffer spanning
    prior boots (tick resets each boot), so a stale earlier-boot ERROR must not pollute the
    verdict. Slice from the last BOOT entry."""
    logs = c.send("get_logs", {"n": n}).get("logs", [])
    last_boot = max((i for i, e in enumerate(logs) if e.get("event") == "BOOT"), default=-1)
    return logs[last_boot + 1 :] if last_boot >= 0 else logs


def _player_op_pos(spec: dict) -> list | None:
    """The arena's `player` op position (the mission's intended start), if it declares one."""
    for op in spec["ops"]:
        if op["op"] == "player":
            return _xyz(op["pos"])
    return None


def _ensure_bot_ready(c: BridgeClient, spec: dict) -> None:
    """The cross-arena flake killer. A prior arena's clean (or this build's own `clear`) can pull
    the floor out from under the bot MID-BUILD — it falls, sometimes dies, and respawns at world
    spawn hundreds of blocks away; the mission then runs from the wrong spot and quietly times
    out/stalls (the roaming one-arena-per-gate FAIL: fetch-chest one run, snow-drill the next).
    Before mission start: respawn if dead (the proven raw LocalPlayer.respawn — RECOVER's auto
    respawn only helps while the worker is ticking a mission), re-tp to the arena's `player` pos,
    verify it landed. Loud but non-fatal on failure — the verdict stays the mission's."""
    for _ in range(5):
        try:
            if float(c.send("get_state", {}).get("health", 0) or 0) > 0:
                break
        except Exception:  # noqa: BLE001 — transient bridge hiccup; retry the health read
            pass
        print("  bot is dead — respawning before mission start")
        c.send(
            "jeval",
            {"code": "Client.runOnMainThread(JavaWrapper.methodToJava(function(){try{Player.getPlayer().getRaw().m_7583_();}catch(e){}})); 'respawned';"},
        )
        time.sleep(2.0)
    pos = _player_op_pos(spec)
    if pos is None:
        return
    p: dict = {}
    for _ in range(2):
        _chat(c, f"/tp @s {pos[0] + 0.5} {pos[1]} {pos[2] + 0.5}")
        time.sleep(1.0)
        try:
            p = c.send("get_state", {}).get("position") or {}
        except Exception:  # noqa: BLE001
            continue
        if abs(p.get("x", 1e9) - (pos[0] + 0.5)) <= 4 and abs(p.get("z", 1e9) - (pos[2] + 0.5)) <= 4:
            return
    print(f"  ⚠ bot not at the arena start after tp (at {p}) — mission may run from the wrong spot")


def run(c: BridgeClient, spec: dict) -> bool:
    build(c, spec)
    mission = spec.get("mission")
    plan = spec.get("plan")  # a plan NAME (string) → plan_start; the orchestrator chains the steps
    checks = spec.get("checks") or []
    if not mission and not plan:
        if not checks:
            print("  no mission/plan — build only")
            return True
        return run_checks(c, checks)  # gate:run-checks-wired
    _reset_worker(c)  # clean IDLE worker before we re-seed + start (off-thread, no deaf-lock)
    _ensure_bot_ready(c, spec)  # alive + standing at the arena start (the cross-arena flake killer)
    marker = spec.get("marker")
    if marker:  # seed AFTER the restart so the drill's init reads it fresh (no worker clobber)
        _seed_marker(c, marker["ore"], int(marker["x"]), int(marker["z"]))
    if plan:
        print(f"  plan_start {plan}")
        c.send("plan_start", {"name": plan})
    else:
        print(f"  mission_start {mission['name']} {mission.get('params', {})}")
        c.send("mission_start", {"name": mission["name"], "params": mission.get("params", {})})

    expect = spec.get("expect", {})
    want = set(expect.get("events", []))
    timeout = float(expect.get("timeout", 60))
    if not want:
        if checks:
            return run_checks(c, checks)  # gate:run-checks-wired
        print("  (no expect.events — not verifying)")
        return True

    seen: set[str] = set()
    erred = False
    deadline = time.time() + timeout
    while time.time() < deadline:
        time.sleep(1.0)
        for ev in _recent_events(c, 100):
            name = ev.get("event", "")
            if name in want:
                seen.add(name)
            if name == "TRANSITION" and ev.get("fields", {}).get("to") == "ERROR":
                erred = True
        if want <= seen:
            break

    missing = want - seen
    ok = not missing and not erred
    mark = "PASS" if ok else "FAIL"
    print(f"  [{mark}] seen={sorted(seen)} missing={sorted(missing)} errored={erred}")
    if checks:
        ok = run_checks(c, checks) and ok  # gate:run-checks-wired
    return ok


def _canon(value: object) -> str:
    """Canonical JSON of a value: `true` is never `1`, `1` is never `1.0`, key order is ignored."""
    return json.dumps(value, sort_keys=True)


def check_outcome(check: dict, reply: dict) -> tuple[bool, str]:
    """One UNMARKED check's verdict from its jeval reply: (passed, the line to print).

    The comparison is on canonical JSON (`_canon`) — a check states the exact value it wants. A
    bridge error is a FAIL that carries the error text, never a skipped check.
    """
    desc = check.get("desc") or check["jeval"][:60]
    if not reply.get("ok"):
        return False, f"[FAIL] {desc}: jeval error: {reply.get('error')}"  # gate:check-jeval-error
    got, want = reply.get("data"), check["expect"]
    if _canon(got) == _canon(want):  # gate:check-value
        return True, f"[PASS] {desc}: {json.dumps(got)}"  # not-a-gate: the pass result of the check
    return False, f"[FAIL] {desc}: got {json.dumps(got)}, expected {json.dumps(want)}"  # gate:check-value


def wrong_outcome(check: dict, reply: dict, twin: dict, twin_passed: bool) -> tuple[bool, str]:
    """A `wrong` check's verdict: it PASSES only when the game REFUSED the wrong claim by giving
    the right answer — its reply succeeded, the value is its unmarked twin's `expect`, and the
    twin itself passed. Any other answer (an error, null, the wrong value, a third value) FAILS.
    """
    desc = check.get("desc") or check["jeval"][:60]
    if not reply.get("ok"):
        return False, f"[FAIL] {desc}: jeval error: {reply.get('error')}"  # gate:wrong-jeval-error
    got = reply.get("data")
    if _canon(got) == _canon(check["expect"]):  # gate:wrong-accepted
        return False, (f"[FAIL] {desc}: got {json.dumps(got)}, the wrong-on-purpose value — "  # gate:wrong-accepted
                       "this check cannot tell right from wrong")
    if not twin_passed:  # gate:wrong-twin-passed
        return False, (f"[FAIL] {desc}: its unmarked twin '{twin.get('desc', twin['jeval'][:60])}' "  # gate:wrong-twin-passed
                       "failed, so the scene is not the one the claim is about")
    if _canon(got) != _canon(twin["expect"]):  # gate:wrong-gets-right-value
        return False, (f"[FAIL] {desc}: got {json.dumps(got)}, which is neither the wrong "  # gate:wrong-gets-right-value
                       f"{json.dumps(check['expect'])} nor the right {json.dumps(twin['expect'])}")
    return True, (f"[PASS] {desc}: refused the wrong {json.dumps(check['expect'])} — got the "  # not-a-gate: the pass result of the check
                  f"right {json.dumps(got)}")


def twin_index(checks: list[dict], i: int) -> int:
    """The index of the one unmarked check with the same jeval as the `wrong` check i."""
    twins = [j for j, ch in enumerate(checks) if not ch.get("wrong") and ch["jeval"] == checks[i]["jeval"]]
    if len(twins) != 1:
        raise SpecError(f"checks[{i}] is marked wrong but has {len(twins)} unmarked twin(s)")  # gate:wrong-has-twin
    return twins[0]  # not-a-gate: returns the one twin found


def run_checks(c: BridgeClient, checks: list[dict]) -> bool:
    """Run every check (all of them, also after a failure) and print one line each. The unmarked
    checks are judged first, so each `wrong` check can be judged against its twin's verdict."""
    replies = [c.send("jeval", {"code": ch["jeval"]}) for ch in checks]
    verdicts: dict[int, tuple[bool, str]] = {}
    for i, ch in enumerate(checks):
        if not ch.get("wrong"):
            verdicts[i] = check_outcome(ch, replies[i])
    for i, ch in enumerate(checks):
        if ch.get("wrong"):
            t = twin_index(checks, i)
            verdicts[i] = wrong_outcome(ch, replies[i], checks[t], verdicts[t][0])  # gate:wrong-twin-passed
    ok = True
    for i in range(len(checks)):
        passed, line = verdicts[i]
        print(f"  {line}")
        ok = ok and passed  # gate:checks-fold
    print(f"  [{'PASS' if ok else 'FAIL'}] checks")
    return ok  # gate:checks-fold


def validate_arena_spec(spec: dict, name: str) -> None:
    """Refuse, before any build, a malformed `checks` list, a known-bad without a marked wrong
    check, and a wrong check without exactly one unmarked twin (same `jeval`, another `expect`)."""
    checks = spec.get("checks")
    if checks is not None:
        if not isinstance(checks, list) or not checks:  # gate:spec-checks-list
            raise SpecError(f"arena '{name}': 'checks' must be a non-empty list")  # gate:spec-checks-list
        for i, ch in enumerate(checks):
            if not isinstance(ch, dict) or not isinstance(ch.get("jeval"), str) or not ch["jeval"].strip():  # gate:spec-check-jeval
                raise SpecError(f"arena '{name}': checks[{i}] needs a non-empty 'jeval' string")  # gate:spec-check-jeval
            if "expect" not in ch:  # gate:spec-check-expect
                raise SpecError(f"arena '{name}': checks[{i}] has no 'expect' value")  # gate:spec-check-expect
            if "wrong" in ch and ch["wrong"] is not True:  # gate:spec-wrong-literal
                raise SpecError(f"arena '{name}': checks[{i}] 'wrong' must be true (or absent)")  # gate:spec-wrong-literal
        for i, ch in enumerate(checks):
            if ch.get("wrong") is True:
                try:
                    t = twin_index(checks, i)
                except SpecError as e:
                    raise SpecError(f"arena '{name}': {e} — a wrong check needs exactly one unmarked "  # gate:wrong-has-twin
                                    "check with the same 'jeval' that expects the right value") from None
                if _canon(checks[t]["expect"]) == _canon(ch["expect"]):  # gate:wrong-twin-differs
                    raise SpecError(f"arena '{name}': checks[{i}] and its twin checks[{t}] expect the "  # gate:wrong-twin-differs
                                    "same value — the twin states the RIGHT one")
    wrong = any(ch.get("wrong") is True for ch in checks or [])
    if "known_bad" in spec:
        if not isinstance(spec["known_bad"], str) or not spec["known_bad"].strip():  # gate:spec-known-bad-text
            raise SpecError(f"arena '{name}': 'known_bad' must say which wrong behaviour it asserts")  # gate:spec-known-bad-text
        if not wrong:
            raise SpecError(f"arena '{name}': a known-bad arena marks its wrong check(s) \"wrong\": true")  # gate:spec-known-bad-marks
    elif wrong:
        raise SpecError(f"arena '{name}': a \"wrong\" check belongs in a known-bad arena (add 'known_bad')")  # gate:spec-wrong-needs-known-bad


def asserts(spec: dict) -> bool:
    """True when the arena verifies anything — the full gate's membership rule."""
    return bool((spec.get("expect") or {}).get("events") or spec.get("checks"))  # gate:asserts-checks


# ── cli ───────────────────────────────────────────────────────────────────────
def _is_set(name: str) -> bool:
    return name.startswith(SET_PREFIX)


def _spec_path(name: str) -> Path:
    """`sets/<name>` → scenarios/sets/<name>.json, anything else → scenarios/arenas/.

    The prefix is the whole isolation mechanism: `_all_names()` globs scenarios/arenas ONLY,
    so `run --all` (and `just gate-live` on top of it) can never pick a film set up.
    """
    if _is_set(name):
        return SETS_DIR / f"{name[len(SET_PREFIX):]}.json"
    return ARENA_DIR / f"{name}.json"


# Canonical key order for a set file, so a re-snapshot is a content diff and not a reshuffle.
# `name` is injected by _load for the log lines and is deliberately NOT persisted.
_SPEC_KEY_ORDER = ("desc", "snapshot", "ops_generated", "ops", "marker")


def _load(name: str) -> dict:
    path = _spec_path(name)
    if not path.exists():
        sys.exit(f"no {'set' if _is_set(name) else 'arena'} '{name}' at {path}")
    spec = json.loads(path.read_text("utf-8"))
    # `name` is DERIVED from the filename below and filtered back out by _dump_spec, so a
    # hand-written one on disk is a lie with no failure mode of its own: it is shadowed at load
    # and silently deleted by the next `snapshot`. Refuse it instead of quietly disagreeing.
    if isinstance(spec, dict) and "name" in spec:
        raise SpecError(
            f"'{name}': the spec file declares a 'name' key — a spec's name is derived from its "
            f"filename ({path.name}) and is never stored; the key is ignored on load and dropped "
            "on the next write. Delete it (and rename the file if THAT is what you meant)"
        )
    if _is_set(name):
        validate_set_spec(spec, name)
    else:
        validate_arena_spec(spec, name)  # gate:load-validates
    spec.setdefault("name", name)
    return spec


def _is_flat(value: object) -> bool:
    """True when a value holds no containers of its own — i.e. it fits on one line."""
    if isinstance(value, dict):
        return all(_is_flat(v) and not isinstance(v, dict) for v in value.values())
    if isinstance(value, list):
        return all(not isinstance(v, (dict, list)) for v in value)
    return True


def _fmt(value: object, pad: str) -> str:
    """JSON with one LEAF object per line: `{"op":"set","pos":[…],"block":"…"}` stays inline,
    containers nest. json.dumps(indent=2) would explode a 300-op generat into 2400 lines and
    make every re-snapshot unreadable as a diff."""
    if _is_flat(value):
        return json.dumps(value, ensure_ascii=False)
    inner = pad + "  "
    if isinstance(value, list):
        return "[\n" + ",\n".join(inner + _fmt(v, inner) for v in value) + f"\n{pad}]"
    if isinstance(value, dict):
        body = ",\n".join(
            f"{inner}{json.dumps(k, ensure_ascii=False)}: {_fmt(v, inner)}" for k, v in value.items()
        )
        return "{\n" + body + f"\n{pad}}}"
    return json.dumps(value, ensure_ascii=False)


def _dump_spec(spec: dict) -> str:
    ordered = [k for k in _SPEC_KEY_ORDER if k in spec]
    ordered += [k for k in spec if k not in ordered and k != "name"]
    body = ",\n".join(
        f"  {json.dumps(k, ensure_ascii=False)}: {_fmt(spec[k], '  ')}" for k in ordered
    )
    return "{\n" + body + "\n}\n"


def _write_spec(name: str, spec: dict) -> None:
    _spec_path(name).write_text(_dump_spec(spec), "utf-8")


def _all_names() -> list[str]:
    """Arena names ONLY — the `--all`/gate surface. Film sets are addressed one by one."""
    return sorted(p.stem for p in ARENA_DIR.glob("*.json"))


def _all_set_names() -> list[str]:
    return sorted(f"{SET_PREFIX}{p.stem}" for p in SETS_DIR.glob("*.json"))


SETS_HEADER = "  -- film sets (staging only, never in `run --all`) --"


def main() -> None:
    ap = argparse.ArgumentParser(description="declarative in-game test-arena/film-set tool")
    ap.add_argument("cmd", choices=["build", "run", "clean", "list", "snapshot"])
    ap.add_argument("name", nargs="?", help="arena name, sets/<name> for a film set (or --all)")
    ap.add_argument("--all", action="store_true", help="apply to every arena (never to sets)")
    # Which client to drive. The default 55544 is the human's own instance — but a film set is
    # BUILT from an OPPED client (the camera is 55546; bots are non-op and the server silently
    # drops their /fill), so the port has to be selectable rather than baked in.
    ap.add_argument("--port", type=int, default=DEFAULT_PORT, help=f"bridge port (default {DEFAULT_PORT}; camera 55546)")
    ap.add_argument("--host", default=None, help="bridge host (default: probe loopback, then the gateway)")
    args = ap.parse_args()

    if args.cmd == "list":
        sets = _all_set_names()
        for n in _all_names() + ([SETS_HEADER] + sets if sets else []):
            if n is SETS_HEADER:
                print(SETS_HEADER)
                continue
            # One unparseable/invalid spec must not blank the whole listing — report it inline.
            try:
                desc = _load(n).get("desc", "")
            except (SpecError, ValueError) as e:
                desc = f"⚠ UNREADABLE: {e}"
            print(f"  {n:18} {desc}")
        return

    names = _all_names() if args.all else ([args.name] if args.name else [])
    if not names:
        sys.exit("need an arena name (or --all)")
    if args.cmd == "snapshot" and (args.all or not all(_is_set(n) for n in names)):
        sys.exit("snapshot works on ONE film set: arena.py snapshot sets/<name>")

    # A snapshot/verify read is a bounded block sweep, not a ping — give it its own socket budget.
    heavy = args.cmd in ("snapshot", "build")
    c = BridgeClient(
        host=args.host, port=args.port, timeout=SNAPSHOT_TIMEOUT if heavy else DEFAULT_TIMEOUT
    )
    results: dict[str, bool] = {}
    for n in names:
        spec = _load(n)
        if args.cmd == "build":
            build(c, spec)
            # Sets are the only WRITE-ONLY build path (no mission verdict follows), so prove the
            # world actually changed. Arenas are verified by the mission the gate then runs.
            if _is_set(n):
                verify_build(c, spec)
        elif args.cmd == "clean":
            clean(c, spec)
        elif args.cmd == "snapshot":
            snapshot(c, n, spec)
        elif args.cmd == "run":
            results[n] = run(c, spec)

    if args.cmd == "run":
        # Exit non-zero if ANY arena failed — single OR multi (so `arena.py run <name>` is usable
        # as a gate step, not just `--all`). Print the roll-up only when more than one ran.
        if len(results) > 1:
            print("\n=== summary ===")
            for n, ok in results.items():
                print(f"  {'PASS' if ok else 'FAIL'}  {n}")
        sys.exit(0 if results and all(results.values()) else 1)


if __name__ == "__main__":
    try:
        main()
    except SpecError as e:  # a bad spec / box / block read is an operator error, not a traceback
        sys.exit(f"arena: {e}")
