// docs/COMMANDS.md is GENERATED: the render of every bridge command row, read offline from the
// source tables (test-ts/_harness-tables.ts) and merged by main.js's own buildManifest — the set
// the live `describe` command serves. The committed file must equal a fresh render; edit the
// source row (main.js META_COMMANDS, an ext.js plugin meta, worker-bundle.ts WORKER_COMMAND_DOCS)
// and regenerate with `just commands-ref`, which runs this file with GERDA_WRITE_COMMANDS=1.
//
// Next to freshness, the rows themselves are checked: every row carries a description, every name
// a container layer dispatches has a row, and every WORKER_COMMAND_DOCS row names a live command.
// Each check is a function of its inputs, so its known-bad runs through the same code.
import { readFileSync, writeFileSync } from "node:fs";
import { env } from "node:process";
import { beforeAll, describe, expect, it } from "vitest";

import {
  type CommandDoc,
  type Manifest,
  block,
  buildManifest,
  containerSources,
  extMetas,
  keys,
  loadBundleWiring,
} from "./_harness-tables";

const OUT = "docs/COMMANDS.md";
const MAIN = "harness/main.js";
const EXT = "harness/ext.js";
const BUNDLE = "src/bot/entry/worker-bundle.ts";

const DIAG = /^DIAG:\s*/;

const GROUPS: { where: string; title: string; source: string; blurb: string }[] = [
  {
    where: "bridge",
    title: "Bridge",
    source: "harness/bridge.js",
    blurb: "Answered by the TCP gateway itself, so they work while main.js is deaf or stale.",
  },
  {
    where: "container",
    title: "Container",
    source: "harness/main.js",
    blurb:
      "The supervisor's own commands: diagnostics, worker lifecycle, eval, and the eyes/hands " +
      "primitives of `harness/screen.js`.",
  },
  {
    where: "ext",
    title: "Ext plugins",
    source: "harness/ext.js",
    blurb: "Mod-API plugins, reloaded live with `reload_ext`.",
  },
  {
    where: "worker",
    title: "Worker bundle",
    source: "src/bot/entry/worker-bundle.ts",
    blurb: "Gerda Bot's own commands, answered by the kernel inside the loaded bundle.",
  },
];

const cell = (s: string): string => s.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|");

function args(d: CommandDoc): string {
  if (d.params.length === 0) return "—";
  return d.params
    .map((p) => {
      const req = p.required === true ? " **required**" : "";
      const desc = p.desc ? ` — ${cell(p.desc)}` : "";
      return `\`${p.name}\` ${p.type}${req}${desc}`;
    })
    .join("<br>");
}

/** The markdown of docs/COMMANDS.md for a merged manifest. */
function renderCommands(m: Manifest): string {
  const names = Object.keys(m).sort();
  const isDiag = (n: string): boolean => DIAG.test(m[n]?.desc ?? "");
  const row = (n: string, d: CommandDoc, layer?: string): string => {
    const lead = layer === undefined ? "" : ` ${layer} |`;
    return `| \`${n}\` |${lead} ${args(d)} | ${cell(d.desc.replace(DIAG, ""))} |`;
  };
  const out: string[] = [
    "<!-- GENERATED by `just commands-ref` from harness/main.js META_COMMANDS, the harness/ext.js",
    "     plugin metas and WORKER_COMMAND_DOCS in src/bot/entry/worker-bundle.ts. Edit those rows,",
    "     never this file: test-ts/commands-ref.test.ts fails the commit when they differ. -->",
    "# Bridge command reference",
    "",
    `Every command the bridge answers — ${names.length} of them. Send one with`,
    "`./gerda ctl send <name> '<json args>'` or the `mc_send` MCP tool; a running bot serves the",
    "same set as the `describe` command and the `mc://api` MCP resource. Where two layers declare",
    "one name, the container row wins, as in dispatch (`harness/main.js#buildManifest`).",
    "",
    "Arguments marked **required** must be present; the rest are optional. A command whose",
    "description starts with `DIAG:` is a diagnostic probe and is listed under",
    "[Diagnostic](#diagnostic) instead of under its layer. The dispatch path behind the layers:",
    "[IPC.md](IPC.md).",
    "",
  ];
  for (const g of GROUPS) {
    const rows = names.filter((n) => m[n]?.where === g.where && !isDiag(n));
    out.push(`## ${g.title}`, "", `\`${g.source}\` — ${g.blurb}`, "");
    out.push("| Command | Arguments | Description |", "|---|---|---|");
    for (const n of rows) out.push(row(n, m[n] as CommandDoc));
    out.push("");
  }
  out.push("## Diagnostic", "", "Probes for testing and debugging; most are idle/paused only.", "");
  out.push("| Command | Layer | Arguments | Description |", "|---|---|---|---|");
  for (const n of names.filter(isDiag)) {
    const d = m[n] as CommandDoc;
    out.push(row(n, d, d.where));
  }
  return `${out.join("\n")}\n`;
}

/** Rows with no description, or a `where` no group renders. */
function badRows(m: Manifest): string[] {
  const layers = new Set(GROUPS.map((g) => g.where));
  return Object.entries(m)
    .filter(([, d]) => !(d.desc.replace(DIAG, "").trim() && layers.has(d.where)))
    .map(([n]) => n);
}

/** Names a container layer dispatches with no manifest row. `_`-names are main.js/screen.js
 *  internal helpers that live in the same maps (`HANDLERS._passthrough`), not commands. */
function undispatchedRows(sources: ReturnType<typeof containerSources>, m: Manifest): string[] {
  const dispatched = new Set([
    ...sources.handlers,
    ...sources.screen,
    ...sources.ext,
    ...sources.bridge,
  ]);
  return [...dispatched].filter((n) => !(n.startsWith("_") || n in m));
}

/** Rows whose `where` is not the layer that answers the name first (bridge.js → main.js HANDLERS
 *  with screen.js → ext.js → the worker), so a row's group in the reference is where it runs. */
function misplacedRows(sources: ReturnType<typeof containerSources>, m: Manifest): string[] {
  const answeredBy = (n: string): string => {
    if (sources.bridge.has(n)) return "bridge";
    if (sources.handlers.has(n) || sources.screen.has(n)) return "container";
    return sources.ext.has(n) ? "ext" : "worker";
  };
  return Object.entries(m)
    .filter(([n, d]) => d.where !== answeredBy(n))
    .map(([n, d]) => `${n}: row says ${d.where}, ${answeredBy(n)} answers it`);
}

/** WORKER_COMMAND_DOCS rows that no registered command answers (a renamed command's dead row). */
function deadDocRows(bundleSrc: string, describe: Manifest): string[] {
  const table = block(bundleSrc, "const WORKER_COMMAND_DOCS", /^};/m);
  return keys(table, /^ {2}(\w+): \{/gm).filter((n) => !(n in describe));
}

describe("docs/COMMANDS.md ↔ the command source tables", () => {
  let describeRows: Manifest;
  let extRows: Manifest;
  let mainSrc: string;
  let committed: string;
  let fresh: string;

  beforeAll(async () => {
    describeRows = (await loadBundleWiring()).describe;
    extRows = extMetas();
    mainSrc = readFileSync(MAIN, "utf8");
    fresh = renderCommands(buildManifest(mainSrc, describeRows, extRows));
    if (env["GERDA_WRITE_COMMANDS"] === "1") writeFileSync(OUT, fresh);
    committed = readFileSync(OUT, "utf8");
  }, 60_000);

  it("the committed file is a fresh render (regenerate: just commands-ref)", () => {
    expect(committed, `${OUT} is stale — run \`just commands-ref\``).toBe(fresh);
  });

  it("every source layer is really read", () => {
    const m = buildManifest(mainSrc, describeRows, extRows);
    for (const n of ["bridge_diag", "diag", "screenshot", "prospect", "mission_start", "smoke"]) {
      expect(m, n).toHaveProperty(n);
    }
    // One row per name: the container's lifecycle start/halt shadow the worker's (dispatch order).
    expect(m["start"]?.where).toBe("container");
    expect(describeRows).toHaveProperty("start");
  });

  it("every row has a description and a known layer", () => {
    expect(badRows(buildManifest(mainSrc, describeRows, extRows))).toEqual([]);
  });

  it("every dispatched container name has a row", () => {
    expect(
      undispatchedRows(containerSources(), buildManifest(mainSrc, describeRows, extRows)),
    ).toEqual([]);
  });

  it("every row's layer is the layer that answers it", () => {
    expect(
      misplacedRows(containerSources(), buildManifest(mainSrc, describeRows, extRows)),
    ).toEqual([]);
  });

  it("every WORKER_COMMAND_DOCS row names a live command", () => {
    expect(deadDocRows(readFileSync(BUNDLE, "utf8"), describeRows)).toEqual([]);
  });

  // ---- known-bads: each check above, fed a source with one fixture defect ----------------------

  const FIX = "zz_fixture_cmd";

  it("KNOWN-BAD: a fixture row in main.js META_COMMANDS makes the render differ", () => {
    const src = mainSrc.replace(
      "var META_COMMANDS = {",
      `var META_COMMANDS = {\n    ${FIX}: {where: "container", desc: "fixture", params: []},`,
    );
    expect(src).not.toBe(mainSrc);
    const r = renderCommands(buildManifest(src, describeRows, extRows));
    expect(r).toContain(`\`${FIX}\``);
    expect(r).not.toBe(committed);
  });

  it("KNOWN-BAD: a fixture ext.js plugin makes the render differ", () => {
    const ext = readFileSync(EXT, "utf8");
    const end = ext.lastIndexOf("})();");
    expect(end).toBeGreaterThan(0);
    const src = `${ext.slice(0, end)}defineCmd("${FIX}", function () {}, {where: "ext", desc: "fixture", params: []});\n${ext.slice(end)}`;
    const r = renderCommands(buildManifest(mainSrc, describeRows, extMetas(src)));
    expect(r).toContain(`\`${FIX}\``);
    expect(r).not.toBe(committed);
  });

  it("KNOWN-BAD: a fixture worker command makes the render differ", () => {
    const worker = { ...describeRows, [FIX]: { where: "worker", desc: "fixture", params: [] } };
    expect(renderCommands(buildManifest(mainSrc, worker, extRows))).not.toBe(committed);
  });

  it("KNOWN-BAD: a live worker command with no doc row is a bad row", () => {
    const worker = { ...describeRows, [FIX]: { where: "worker", desc: "", params: [] } };
    expect(badRows(buildManifest(mainSrc, worker, extRows))).toEqual([FIX]);
    const diagOnly = { ...describeRows, [FIX]: { where: "worker", desc: "DIAG: ", params: [] } };
    expect(badRows(buildManifest(mainSrc, diagOnly, extRows))).toEqual([FIX]);
  });

  it("KNOWN-BAD: a main.js handler with no META_COMMANDS row is reported", () => {
    const src = mainSrc.replace(
      "var HANDLERS = {",
      `var HANDLERS = {\n    ${FIX}: function (_req, id) {},`,
    );
    expect(src).not.toBe(mainSrc);
    const sources = containerSources({ [MAIN]: src });
    expect(undispatchedRows(sources, buildManifest(mainSrc, describeRows, extRows))).toEqual([FIX]);
  });

  it("KNOWN-BAD: a META_COMMANDS row claiming the wrong layer is reported", () => {
    const src = mainSrc.replace(/ping: +\{where: "bridge"/, 'ping: {where: "container"');
    expect(src).not.toBe(mainSrc);
    expect(misplacedRows(containerSources(), buildManifest(src, describeRows, extRows))).toEqual([
      "ping: row says container, bridge answers it",
    ]);
  });

  it("KNOWN-BAD: a WORKER_COMMAND_DOCS row no command answers is reported", () => {
    const orig = readFileSync(BUNDLE, "utf8");
    const src = orig.replace("> = {\n", `> = {\n  ${FIX}: { desc: "fixture", params: [] },\n`);
    expect(src).not.toBe(orig);
    expect(deadDocRows(src, describeRows)).toEqual([FIX]);
  });
});
